#include "textflag.h"

// func dotF32Tile4x4(a, b *float32, k, aStride, bStride int, out *float32)
//
// out[i*4+j] = Σ_{c<k} a[i*aStride+c] * b[j*bStride+c], i, j in 0..3, k a
// positive multiple of 4; strides in elements. 16 lane-wise FMLA
// accumulators, folded with FADDP at the end.
TEXT ·dotF32Tile4x4(SB), NOSPLIT, $0-48
	MOVD a+0(FP), R0
	MOVD b+8(FP), R4
	MOVD k+16(FP), R8
	MOVD aStride+24(FP), R9
	MOVD bStride+32(FP), R10
	MOVD out+40(FP), R11
	LSL  $2, R9, R9
	LSL  $2, R10, R10
	ADD  R9, R0, R1
	ADD  R9, R1, R2
	ADD  R9, R2, R3
	ADD  R10, R4, R5
	ADD  R10, R5, R6
	ADD  R10, R6, R7

	VEOR V16.B16, V16.B16, V16.B16
	VEOR V17.B16, V17.B16, V17.B16
	VEOR V18.B16, V18.B16, V18.B16
	VEOR V19.B16, V19.B16, V19.B16
	VEOR V20.B16, V20.B16, V20.B16
	VEOR V21.B16, V21.B16, V21.B16
	VEOR V22.B16, V22.B16, V22.B16
	VEOR V23.B16, V23.B16, V23.B16
	VEOR V24.B16, V24.B16, V24.B16
	VEOR V25.B16, V25.B16, V25.B16
	VEOR V26.B16, V26.B16, V26.B16
	VEOR V27.B16, V27.B16, V27.B16
	VEOR V28.B16, V28.B16, V28.B16
	VEOR V29.B16, V29.B16, V29.B16
	VEOR V30.B16, V30.B16, V30.B16
	VEOR V31.B16, V31.B16, V31.B16
	LSR  $2, R8, R8

dloop:
	VLD1.P 16(R0), [V0.S4]
	VLD1.P 16(R1), [V1.S4]
	VLD1.P 16(R2), [V2.S4]
	VLD1.P 16(R3), [V3.S4]
	VLD1.P 16(R4), [V4.S4]
	VLD1.P 16(R5), [V5.S4]
	VLD1.P 16(R6), [V6.S4]
	VLD1.P 16(R7), [V7.S4]
	VFMLA V4.S4, V0.S4, V16.S4
	VFMLA V5.S4, V0.S4, V17.S4
	VFMLA V6.S4, V0.S4, V18.S4
	VFMLA V7.S4, V0.S4, V19.S4
	VFMLA V4.S4, V1.S4, V20.S4
	VFMLA V5.S4, V1.S4, V21.S4
	VFMLA V6.S4, V1.S4, V22.S4
	VFMLA V7.S4, V1.S4, V23.S4
	VFMLA V4.S4, V2.S4, V24.S4
	VFMLA V5.S4, V2.S4, V25.S4
	VFMLA V6.S4, V2.S4, V26.S4
	VFMLA V7.S4, V2.S4, V27.S4
	VFMLA V4.S4, V3.S4, V28.S4
	VFMLA V5.S4, V3.S4, V29.S4
	VFMLA V6.S4, V3.S4, V30.S4
	VFMLA V7.S4, V3.S4, V31.S4
	SUBS $1, R8, R8
	BNE  dloop

	// faddp vD.4s, vN.4s, vM.4s = 0x6E20D400 | M<<16 | N<<5 | D (pairs the
	// four lanes into two), then faddp sD, vN.2s = 0x7E30D800 | N<<5 | D.
	WORD $0x6E30D610
	WORD $0x7E30DA10
	FMOVS F16, 0(R11)
	WORD $0x6E31D631
	WORD $0x7E30DA31
	FMOVS F17, 4(R11)
	WORD $0x6E32D652
	WORD $0x7E30DA52
	FMOVS F18, 8(R11)
	WORD $0x6E33D673
	WORD $0x7E30DA73
	FMOVS F19, 12(R11)
	WORD $0x6E34D694
	WORD $0x7E30DA94
	FMOVS F20, 16(R11)
	WORD $0x6E35D6B5
	WORD $0x7E30DAB5
	FMOVS F21, 20(R11)
	WORD $0x6E36D6D6
	WORD $0x7E30DAD6
	FMOVS F22, 24(R11)
	WORD $0x6E37D6F7
	WORD $0x7E30DAF7
	FMOVS F23, 28(R11)
	WORD $0x6E38D718
	WORD $0x7E30DB18
	FMOVS F24, 32(R11)
	WORD $0x6E39D739
	WORD $0x7E30DB39
	FMOVS F25, 36(R11)
	WORD $0x6E3AD75A
	WORD $0x7E30DB5A
	FMOVS F26, 40(R11)
	WORD $0x6E3BD77B
	WORD $0x7E30DB7B
	FMOVS F27, 44(R11)
	WORD $0x6E3CD79C
	WORD $0x7E30DB9C
	FMOVS F28, 48(R11)
	WORD $0x6E3DD7BD
	WORD $0x7E30DBBD
	FMOVS F29, 52(R11)
	WORD $0x6E3ED7DE
	WORD $0x7E30DBDE
	FMOVS F30, 56(R11)
	WORD $0x6E3FD7FF
	WORD $0x7E30DBFF
	FMOVS F31, 60(R11)
	RET

// func axpyTile4x16(p *float32, pStride int, v *float32, vStride int, n int, out *float32, outStride int)
//
// out[i*outStride+d] = Σ_{j<n} p[i*pStride+j] * v[j*vStride+d] for i in
// 0..3, d in 0..15; n ≥ 1; strides in elements. Four scalar weights per
// step, FMLA by element into 4×4 vector accumulators.
TEXT ·axpyTile4x16(SB), NOSPLIT, $0-56
	MOVD p+0(FP), R0
	MOVD pStride+8(FP), R9
	MOVD v+16(FP), R4
	MOVD vStride+24(FP), R10
	MOVD n+32(FP), R8
	MOVD out+40(FP), R11
	MOVD outStride+48(FP), R12
	LSL  $2, R9, R9
	LSL  $2, R10, R10
	LSL  $2, R12, R12
	ADD  R9, R0, R1
	ADD  R9, R1, R2
	ADD  R9, R2, R3

	VEOR V16.B16, V16.B16, V16.B16
	VEOR V17.B16, V17.B16, V17.B16
	VEOR V18.B16, V18.B16, V18.B16
	VEOR V19.B16, V19.B16, V19.B16
	VEOR V20.B16, V20.B16, V20.B16
	VEOR V21.B16, V21.B16, V21.B16
	VEOR V22.B16, V22.B16, V22.B16
	VEOR V23.B16, V23.B16, V23.B16
	VEOR V24.B16, V24.B16, V24.B16
	VEOR V25.B16, V25.B16, V25.B16
	VEOR V26.B16, V26.B16, V26.B16
	VEOR V27.B16, V27.B16, V27.B16
	VEOR V28.B16, V28.B16, V28.B16
	VEOR V29.B16, V29.B16, V29.B16
	VEOR V30.B16, V30.B16, V30.B16
	VEOR V31.B16, V31.B16, V31.B16

aloop:
	VLD1 (R4), [V0.S4, V1.S4, V2.S4, V3.S4]
	ADD  R10, R4, R4
	FMOVS.P 4(R0), F4
	FMOVS.P 4(R1), F5
	FMOVS.P 4(R2), F6
	FMOVS.P 4(R3), F7
	// fmla vD.4s, vN.4s, vM.s[0] = 0x4F801000 | M<<16 | N<<5 | D
	WORD $0x4F841010 // v16 += v0 * v4.s[0]
	WORD $0x4F841031 // v17 += v1 * v4.s[0]
	WORD $0x4F841052 // v18 += v2 * v4.s[0]
	WORD $0x4F841073 // v19 += v3 * v4.s[0]
	WORD $0x4F851014 // v20 += v0 * v5.s[0]
	WORD $0x4F851035
	WORD $0x4F851056
	WORD $0x4F851077
	WORD $0x4F861018 // v24 += v0 * v6.s[0]
	WORD $0x4F861039
	WORD $0x4F86105A
	WORD $0x4F86107B
	WORD $0x4F87101C // v28 += v0 * v7.s[0]
	WORD $0x4F87103D
	WORD $0x4F87105E
	WORD $0x4F87107F
	SUBS $1, R8, R8
	BNE  aloop

	VST1 [V16.S4, V17.S4, V18.S4, V19.S4], (R11)
	ADD  R12, R11, R11
	VST1 [V20.S4, V21.S4, V22.S4, V23.S4], (R11)
	ADD  R12, R11, R11
	VST1 [V24.S4, V25.S4, V26.S4, V27.S4], (R11)
	ADD  R12, R11, R11
	VST1 [V28.S4, V29.S4, V30.S4, V31.S4], (R11)
	RET
