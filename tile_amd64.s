#include "textflag.h"

// func gemmTileAVX2(a, b *byte, k, ncb, bStride int, xs, ws *float32, corr *int32, out *float32, outStride int)
//
// Eight activation rows (a, row-major unsigned bytes, k apart) against
// ncb blocks of eight weight rows (b, [k/4][8][4] int8, bStride bytes
// apart), k a positive multiple of 4:
// out[r*outStride+c] = xs[r] * ws[c] * (Σ a[r]·b[c] - corr[c]).
// Per step of four k: one 32-byte weight load, eight 4-byte activation
// broadcasts, and per row VPMADDUBSW (u8·s8 pairs to int16), VPMADDWD by
// ones (to int32) and VPADDD into the row's accumulator.
TEXT ·gemmTileAVX2(SB), NOSPLIT, $0-80
	MOVQ b+8(FP), BX
	MOVQ k+16(FP), DX
	MOVQ ncb+24(FP), CX
	MOVQ bStride+32(FP), SI
	MOVQ xs+40(FP), R8
	MOVQ ws+48(FP), R9
	MOVQ corr+56(FP), R10
	MOVQ out+64(FP), DI
	MOVQ outStride+72(FP), R11
	SHLQ $2, R11
	VPCMPEQW Y11, Y11, Y11
	VPSRLW   $15, Y11, Y11 // int16 ones

colblock:
	VPXOR Y0, Y0, Y0
	VPXOR Y1, Y1, Y1
	VPXOR Y2, Y2, Y2
	VPXOR Y3, Y3, Y3
	VPXOR Y4, Y4, Y4
	VPXOR Y5, Y5, Y5
	VPXOR Y6, Y6, Y6
	VPXOR Y7, Y7, Y7
	MOVQ a+0(FP), R12      // rows 0..2 at R12 + {0, k, 2k}
	LEAQ (R12)(DX*2), R13
	ADDQ DX, R13           // rows 3..5 at R13 + {0, k, 2k}
	LEAQ (R13)(DX*2), R14
	ADDQ DX, R14           // rows 6, 7 at R14 + {0, k}
	MOVQ BX, R15
	MOVQ DX, AX
	SHRQ $2, AX

step:
	VMOVDQU (R15), Y8
	VPBROADCASTD (R12), Y9
	VPMADDUBSW Y8, Y9, Y10
	VPMADDWD Y11, Y10, Y10
	VPADDD Y10, Y0, Y0
	VPBROADCASTD (R12)(DX*1), Y9
	VPMADDUBSW Y8, Y9, Y10
	VPMADDWD Y11, Y10, Y10
	VPADDD Y10, Y1, Y1
	VPBROADCASTD (R12)(DX*2), Y9
	VPMADDUBSW Y8, Y9, Y10
	VPMADDWD Y11, Y10, Y10
	VPADDD Y10, Y2, Y2
	VPBROADCASTD (R13), Y9
	VPMADDUBSW Y8, Y9, Y10
	VPMADDWD Y11, Y10, Y10
	VPADDD Y10, Y3, Y3
	VPBROADCASTD (R13)(DX*1), Y9
	VPMADDUBSW Y8, Y9, Y10
	VPMADDWD Y11, Y10, Y10
	VPADDD Y10, Y4, Y4
	VPBROADCASTD (R13)(DX*2), Y9
	VPMADDUBSW Y8, Y9, Y10
	VPMADDWD Y11, Y10, Y10
	VPADDD Y10, Y5, Y5
	VPBROADCASTD (R14), Y9
	VPMADDUBSW Y8, Y9, Y10
	VPMADDWD Y11, Y10, Y10
	VPADDD Y10, Y6, Y6
	VPBROADCASTD (R14)(DX*1), Y9
	VPMADDUBSW Y8, Y9, Y10
	VPMADDWD Y11, Y10, Y10
	VPADDD Y10, Y7, Y7
	ADDQ $4, R12
	ADDQ $4, R13
	ADDQ $4, R14
	ADDQ $32, R15
	DECQ AX
	JNZ  step

	// Epilogue: minus the offset correction, to float32, times the column
	// scales and the row scale.
	VMOVDQU (R10), Y8
	VMOVUPS (R9), Y9
	MOVQ DI, R12
	VPSUBD Y8, Y0, Y0
	VCVTDQ2PS Y0, Y0
	VMULPS Y9, Y0, Y0
	VBROADCASTSS 0(R8), Y10
	VMULPS Y10, Y0, Y0
	VMOVUPS Y0, (R12)
	ADDQ R11, R12
	VPSUBD Y8, Y1, Y1
	VCVTDQ2PS Y1, Y1
	VMULPS Y9, Y1, Y1
	VBROADCASTSS 4(R8), Y10
	VMULPS Y10, Y1, Y1
	VMOVUPS Y1, (R12)
	ADDQ R11, R12
	VPSUBD Y8, Y2, Y2
	VCVTDQ2PS Y2, Y2
	VMULPS Y9, Y2, Y2
	VBROADCASTSS 8(R8), Y10
	VMULPS Y10, Y2, Y2
	VMOVUPS Y2, (R12)
	ADDQ R11, R12
	VPSUBD Y8, Y3, Y3
	VCVTDQ2PS Y3, Y3
	VMULPS Y9, Y3, Y3
	VBROADCASTSS 12(R8), Y10
	VMULPS Y10, Y3, Y3
	VMOVUPS Y3, (R12)
	ADDQ R11, R12
	VPSUBD Y8, Y4, Y4
	VCVTDQ2PS Y4, Y4
	VMULPS Y9, Y4, Y4
	VBROADCASTSS 16(R8), Y10
	VMULPS Y10, Y4, Y4
	VMOVUPS Y4, (R12)
	ADDQ R11, R12
	VPSUBD Y8, Y5, Y5
	VCVTDQ2PS Y5, Y5
	VMULPS Y9, Y5, Y5
	VBROADCASTSS 20(R8), Y10
	VMULPS Y10, Y5, Y5
	VMOVUPS Y5, (R12)
	ADDQ R11, R12
	VPSUBD Y8, Y6, Y6
	VCVTDQ2PS Y6, Y6
	VMULPS Y9, Y6, Y6
	VBROADCASTSS 24(R8), Y10
	VMULPS Y10, Y6, Y6
	VMOVUPS Y6, (R12)
	ADDQ R11, R12
	VPSUBD Y8, Y7, Y7
	VCVTDQ2PS Y7, Y7
	VMULPS Y9, Y7, Y7
	VBROADCASTSS 28(R8), Y10
	VMULPS Y10, Y7, Y7
	VMOVUPS Y7, (R12)

	ADDQ $32, DI
	ADDQ $32, R9
	ADDQ $32, R10
	ADDQ SI, BX
	DECQ CX
	JNZ  colblock
	VZEROUPPER
	RET

// func gemmTileVNNI(a, b *byte, k, ncb, bStride int, xs, ws *float32, corr *int32, out *float32, outStride int)
//
// As gemmTileAVX2 with blocks of sixteen weight rows ([k/4][16][4]) and
// VPDPBUSD (four u8·s8 products per int32 lane) into the accumulators.
TEXT ·gemmTileVNNI(SB), NOSPLIT, $0-80
	MOVQ b+8(FP), BX
	MOVQ k+16(FP), DX
	MOVQ ncb+24(FP), CX
	MOVQ bStride+32(FP), SI
	MOVQ xs+40(FP), R8
	MOVQ ws+48(FP), R9
	MOVQ corr+56(FP), R10
	MOVQ out+64(FP), DI
	MOVQ outStride+72(FP), R11
	SHLQ $2, R11

vcolblock:
	VPXORD Z0, Z0, Z0
	VPXORD Z1, Z1, Z1
	VPXORD Z2, Z2, Z2
	VPXORD Z3, Z3, Z3
	VPXORD Z4, Z4, Z4
	VPXORD Z5, Z5, Z5
	VPXORD Z6, Z6, Z6
	VPXORD Z7, Z7, Z7
	MOVQ a+0(FP), R12
	LEAQ (R12)(DX*2), R13
	ADDQ DX, R13
	LEAQ (R13)(DX*2), R14
	ADDQ DX, R14
	MOVQ BX, R15
	MOVQ DX, AX
	SHRQ $2, AX

vstep:
	VMOVDQU64 (R15), Z8
	VPBROADCASTD (R12), Z9
	VPDPBUSD Z8, Z9, Z0
	VPBROADCASTD (R12)(DX*1), Z9
	VPDPBUSD Z8, Z9, Z1
	VPBROADCASTD (R12)(DX*2), Z9
	VPDPBUSD Z8, Z9, Z2
	VPBROADCASTD (R13), Z9
	VPDPBUSD Z8, Z9, Z3
	VPBROADCASTD (R13)(DX*1), Z9
	VPDPBUSD Z8, Z9, Z4
	VPBROADCASTD (R13)(DX*2), Z9
	VPDPBUSD Z8, Z9, Z5
	VPBROADCASTD (R14), Z9
	VPDPBUSD Z8, Z9, Z6
	VPBROADCASTD (R14)(DX*1), Z9
	VPDPBUSD Z8, Z9, Z7
	ADDQ $4, R12
	ADDQ $4, R13
	ADDQ $4, R14
	ADDQ $64, R15
	DECQ AX
	JNZ  vstep

	VMOVDQU32 (R10), Z8
	VMOVUPS (R9), Z9
	MOVQ DI, R12
	VPSUBD Z8, Z0, Z0
	VCVTDQ2PS Z0, Z0
	VMULPS Z9, Z0, Z0
	VBROADCASTSS 0(R8), Z10
	VMULPS Z10, Z0, Z0
	VMOVUPS Z0, (R12)
	ADDQ R11, R12
	VPSUBD Z8, Z1, Z1
	VCVTDQ2PS Z1, Z1
	VMULPS Z9, Z1, Z1
	VBROADCASTSS 4(R8), Z10
	VMULPS Z10, Z1, Z1
	VMOVUPS Z1, (R12)
	ADDQ R11, R12
	VPSUBD Z8, Z2, Z2
	VCVTDQ2PS Z2, Z2
	VMULPS Z9, Z2, Z2
	VBROADCASTSS 8(R8), Z10
	VMULPS Z10, Z2, Z2
	VMOVUPS Z2, (R12)
	ADDQ R11, R12
	VPSUBD Z8, Z3, Z3
	VCVTDQ2PS Z3, Z3
	VMULPS Z9, Z3, Z3
	VBROADCASTSS 12(R8), Z10
	VMULPS Z10, Z3, Z3
	VMOVUPS Z3, (R12)
	ADDQ R11, R12
	VPSUBD Z8, Z4, Z4
	VCVTDQ2PS Z4, Z4
	VMULPS Z9, Z4, Z4
	VBROADCASTSS 16(R8), Z10
	VMULPS Z10, Z4, Z4
	VMOVUPS Z4, (R12)
	ADDQ R11, R12
	VPSUBD Z8, Z5, Z5
	VCVTDQ2PS Z5, Z5
	VMULPS Z9, Z5, Z5
	VBROADCASTSS 20(R8), Z10
	VMULPS Z10, Z5, Z5
	VMOVUPS Z5, (R12)
	ADDQ R11, R12
	VPSUBD Z8, Z6, Z6
	VCVTDQ2PS Z6, Z6
	VMULPS Z9, Z6, Z6
	VBROADCASTSS 24(R8), Z10
	VMULPS Z10, Z6, Z6
	VMOVUPS Z6, (R12)
	ADDQ R11, R12
	VPSUBD Z8, Z7, Z7
	VCVTDQ2PS Z7, Z7
	VMULPS Z9, Z7, Z7
	VBROADCASTSS 28(R8), Z10
	VMULPS Z10, Z7, Z7
	VMOVUPS Z7, (R12)

	ADDQ $64, DI
	ADDQ $64, R9
	ADDQ $64, R10
	ADDQ SI, BX
	DECQ CX
	JNZ  vcolblock
	VZEROUPPER
	RET
